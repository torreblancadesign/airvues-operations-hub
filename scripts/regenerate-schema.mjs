// Regenerates lib/schema.ts from the live Airtable Meta API.
//
//   node scripts/regenerate-schema.mjs          # writes lib/schema.ts
//   node scripts/regenerate-schema.mjs --check  # prints drift, writes nothing
//
// The KEY_OVERRIDES map below pins the `Tables.<Key>` names that existing code
// already imports. Never rename one of those keys — it silently breaks every
// call site. New tables get a key derived from their display name.
//
// Verify afterwards with: npm run verify-schema && npx tsc --noEmit

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, "..");
const OUT = join(REPO, "lib", "schema.ts");

const BASE_ID = process.env.AIRTABLE_BASE_ID || "app4vhhWMbRFOloOU";

function loadToken() {
  if (process.env.AIRTABLE_TOKEN) return process.env.AIRTABLE_TOKEN;
  try {
    const env = readFileSync(join(REPO, ".env.local"), "utf8");
    const m = env.match(/^AIRTABLE_TOKEN=(.+)$/m);
    if (m) return m[1].trim();
  } catch {
    /* no .env.local */
  }
  return null;
}

const TOKEN = loadToken();
if (!TOKEN) {
  console.error("AIRTABLE_TOKEN not set (env or .env.local).");
  process.exit(1);
}

